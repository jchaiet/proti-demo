import fs from "node:fs/promises";
import { execFileSync } from "node:child_process";
import path from "node:path";
import process from "node:process";
import { createInterface } from "node:readline/promises";

const ROOT = process.cwd();
const FLAGS = process.argv.slice(2);
const NEW_PROJECT_FLAG = "--new-project";
const GIT_RESET_CONFIRMATION = "RESET GIT HISTORY";
if (
  FLAGS.some((flag) => flag !== NEW_PROJECT_FLAG) ||
  FLAGS.filter((flag) => flag === NEW_PROJECT_FLAG).length > 1
) {
  throw new Error("Usage: pnpm proti:init [--new-project]");
}
const NEW_PROJECT = FLAGS.includes(NEW_PROJECT_FLAG);
const CONFIG_PATH = path.join(ROOT, "proti.config.json");
const WEB_ENV_PATH = path.join(ROOT, "web", ".env.local");
const STUDIO_ENV_PATH = path.join(ROOT, "studio", ".env.local");
const STUDIO_DEV_ENV_PATH = path.join(ROOT, "studio", ".env.development");
const STUDIO_PROD_ENV_PATH = path.join(ROOT, "studio", ".env.production");

function slugify(value) {
  return value
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

function normalizeLocale(value) {
  return value.trim().toLowerCase();
}

function normalizeDomain(value) {
  return value
    .trim()
    .toLowerCase()
    .replace(/^https?:\/\//, "")
    .replace(/\/.*$/, "")
    .replace(/\.$/, "");
}

function normalizeWebUrl(value, { production = false } = {}) {
  const raw = String(value ?? "").trim();
  if (!raw && production) return "";

  let url;
  try {
    url = new URL(raw);
  } catch {
    throw new Error(
      `Invalid ${production ? "production" : "development"} preview URL "${raw}". Use a full http(s) URL.`,
    );
  }

  if (
    !["http:", "https:"].includes(url.protocol) ||
    !url.hostname ||
    url.username ||
    url.password ||
    url.search ||
    url.hash ||
    url.pathname !== "/"
  ) {
    throw new Error(
      `Invalid preview URL "${raw}". Use a Web origin such as https://example.com (no path, query, or credentials).`,
    );
  }

  if (
    production &&
    (url.protocol !== "https:" ||
      ["localhost", "127.0.0.1", "::1", "[::1]"].includes(
        url.hostname.toLowerCase(),
      ))
  ) {
    throw new Error(
      "Production preview URL must be a public HTTPS origin, not localhost.",
    );
  }

  return url.origin;
}

function suggestedProductionUrl(domain) {
  if (!domain || ["localhost", "127.0.0.1", "example.com"].includes(domain)) {
    return "";
  }
  return `https://${domain}`;
}

// Modify only the managed URL; leave unrelated mode-specific environment
// values/comments intact. Configurations may already have editor additions.
async function updateModePreviewUrl(filePath, previewUrl, heading) {
  const existing = (await fileExists(filePath))
    ? await fs.readFile(filePath, "utf8")
    : "";
  const lines = existing
    ? existing
        .split(/\r?\n/)
        .filter((line) => !/^\s*SANITY_STUDIO_PREVIEW_URL\s*=/.test(line))
    : [
        `# ${heading}`,
        "# Generated by Proti; non-secret public configuration",
        "",
      ];

  while (lines.length && lines.at(-1) === "") lines.pop();
  lines.push(`SANITY_STUDIO_PREVIEW_URL=${envValue(previewUrl)}`, "");

  await fs.mkdir(path.dirname(filePath), { recursive: true });
  await fs.writeFile(filePath, lines.join("\n"));
}

function validateDomain(value) {
  if (!value) {
    throw new Error("Site domains cannot be empty.");
  }

  if (value.includes(":")) {
    throw new Error(`Site domain "${value}" must not include a port.`);
  }

  const labels = value.split(".");

  const invalidLabel = labels.find(
    (label) =>
      !label ||
      label.length > 63 ||
      !/^[a-z0-9-]+$/i.test(label) ||
      label.startsWith("-") ||
      label.endsWith("-"),
  );

  if (invalidLabel) {
    throw new Error(`Site domain "${value}" is not a valid hostname.`);
  }

  return value;
}

function splitCsv(value) {
  return value
    .split(",")
    .map((item) => item.trim())
    .filter(Boolean);
}

function parseLocales(value) {
  const seen = new Set();

  return splitCsv(value).map((entry) => {
    const separator = entry.indexOf(":");
    const rawCode = separator >= 0 ? entry.slice(0, separator) : entry;
    const rawLabel = separator >= 0 ? entry.slice(separator + 1) : entry;
    const code = normalizeLocale(rawCode);
    const label = rawLabel.trim() || code;

    if (!/^[a-z]{2,3}-[a-z]{2}$/.test(code)) {
      throw new Error(
        `Invalid locale "${code}". Proti uses language-region format, e.g. en-us or fr-ca.`,
      );
    }

    if (seen.has(code)) {
      throw new Error(`Duplicate locale "${code}".`);
    }

    seen.add(code);
    return { code, label };
  });
}

async function fileExists(filePath) {
  try {
    await fs.access(filePath);
    return true;
  } catch {
    return false;
  }
}

async function readJson(filePath, fallback = null) {
  if (!(await fileExists(filePath))) return fallback;
  return JSON.parse(await fs.readFile(filePath, "utf8"));
}

function parseEnv(source) {
  const values = {};

  for (const rawLine of source.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith("#")) continue;

    const index = line.indexOf("=");
    if (index < 0) continue;

    const key = line.slice(0, index).trim();
    let value = line.slice(index + 1).trim();

    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }

    values[key] = value;
  }

  return values;
}

async function readEnv(filePath) {
  if (!(await fileExists(filePath))) return {};
  return parseEnv(await fs.readFile(filePath, "utf8"));
}

function envValue(value) {
  const stringValue = String(value ?? "");
  return /[\s#"'`]/.test(stringValue)
    ? JSON.stringify(stringValue)
    : stringValue;
}

async function writeEnv(filePath, values, heading) {
  const content = [
    `# ${heading}`,
    "# Generated by pnpm proti:init",
    "",
    ...Object.entries(values).map(
      ([key, value]) => `${key}=${envValue(value)}`,
    ),
    "",
  ].join("\n");

  await fs.mkdir(path.dirname(filePath), { recursive: true });
  await fs.writeFile(filePath, content);
}

async function prompt(rl, scriptedAnswers, state, label, fallback = "") {
  const suffix = fallback ? ` [${fallback}]` : "";

  if (scriptedAnswers) {
    const answer = (scriptedAnswers[state.index++] ?? "").trim();
    console.log(`${label}${suffix}: ${answer}`);
    return answer || fallback;
  }

  const answer = (await rl.question(`${label}${suffix}: `)).trim();
  return answer || fallback;
}

async function readScriptedAnswers() {
  if (process.stdin.isTTY) return null;

  let input = "";
  for await (const chunk of process.stdin) input += chunk;
  return input.split(/\r?\n/);
}

async function updatePackageName(filePath, name) {
  if (!(await fileExists(filePath))) return;
  const pkg = JSON.parse(await fs.readFile(filePath, "utf8"));
  pkg.name = name;
  await fs.writeFile(filePath, `${JSON.stringify(pkg, null, 2)}\n`);
}

// Git settings are stored locally inside .git/config. Unlike a tracked marker,
// they are not copied by `git clone`, so each new clone can initialize safely.
function git(args) {
  return execFileSync("git", args, {
    cwd: ROOT,
    encoding: "utf8",
    stdio: ["ignore", "pipe", "pipe"],
  }).trim();
}

function tryGit(args) {
  try {
    return git(args);
  } catch {
    return null;
  }
}

function isProtiStarterRemote(url) {
  if (!url) return false;
  const normalized = url
    .trim()
    .replace(/\/+$/, "")
    .replace(/\.git$/i, "");
  return /(?:^|[/:])proti-demo$/i.test(normalized);
}

// There is no reliable way to distinguish the original starter repository
// from a Git clone based on the remote URL alone. Never detach either without
// an explicit --new-project flag AND an exact typed acknowledgement.
async function inspectProjectGit() {
  const gitPath = path.join(ROOT, ".git");
  const gitRoot = tryGit(["rev-parse", "--show-toplevel"]);
  if (gitRoot && path.resolve(gitRoot) !== path.resolve(ROOT)) {
    throw new Error(
      "This directory belongs to a parent Git repository. Run initialization at the project root.",
    );
  }

  let gitEntry;
  try {
    gitEntry = await fs.lstat(gitPath);
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }

  if (!gitEntry) {
    return { mode: "new-repository" };
  }

  if (!gitEntry.isDirectory() || gitEntry.isSymbolicLink()) {
    if (NEW_PROJECT) {
      throw new Error(
        "Refusing --new-project: .git is a worktree, submodule, or symlink.",
      );
    }
    return {
      mode: "preserve-repository",
      firstInitialization: true,
      markInitialized: false,
    };
  }

  // This local-only Git setting identifies the maintained starter repository.
  // It is not transferred by git clone. Refuse all initialization there,
  // including --new-project, before editing any configuration or Git metadata.
  if (
    tryGit(["config", "--local", "--get", "proti.sourceRepository"]) === "true"
  ) {
    throw new Error(
      "This is the maintained Proti source repository (proti.sourceRepository=true). " +
        "Initialization is disabled here to protect its Git history and configuration. " +
        "Create a separate clone to initialize a new project.",
    );
  }

  if (tryGit(["config", "--local", "--get", "proti.initialized"]) === "true") {
    if (NEW_PROJECT) {
      throw new Error(
        "This Proti project is already initialized. Refusing to reset its Git history.",
      );
    }
    return { mode: "preserve-repository", firstInitialization: false };
  }

  const origin = tryGit(["remote", "get-url", "origin"]);
  if (!isProtiStarterRemote(origin)) {
    if (NEW_PROJECT) {
      throw new Error(
        "Refusing --new-project: this repository does not have the expected Proti starter origin. Its Git history will be preserved.",
      );
    }
    return {
      mode: "preserve-repository",
      firstInitialization: true,
      markInitialized: true,
    };
  }

  if (!NEW_PROJECT) {
    throw new Error(
      "This repository still points to the Proti starter. Nothing was changed. " +
        'For an intentional fresh clone, run "pnpm proti:init --new-project" and confirm the Git reset. ' +
        "Never run that command in the original starter repository.",
    );
  }

  // Prevent accidental deletion of user work, including untracked files.
  // This happens BEFORE config, package, or environment files are rewritten.
  const changes = tryGit(["status", "--porcelain", "--untracked-files=normal"]);
  if (changes === null || changes) {
    throw new Error(
      "Refusing --new-project: the working tree contains changes or untracked files. " +
        "Commit or back them up before creating independent history.",
    );
  }

  const remotes = tryGit(["remote"]);
  if (
    remotes !== "origin" ||
    !isProtiStarterRemote(tryGit(["remote", "get-url", "--push", "origin"]))
  ) {
    throw new Error(
      "Refusing --new-project: unexpected Git remotes or push URL detected. " +
        "Only an unchanged starter clone can be detached.",
    );
  }
  return { mode: "detach-starter", gitPath };
}

async function confirmHistoryReset(rl, scriptedAnswers, scriptedState) {
  const acknowledgement = await prompt(
    rl,
    scriptedAnswers,
    scriptedState,
    `To permanently disconnect this clone's Git history, type ${GIT_RESET_CONFIRMATION}`,
  );
  if (acknowledgement !== GIT_RESET_CONFIRMATION) {
    throw new Error(
      "Git history reset was not confirmed. No files or Git metadata were changed.",
    );
  }
}

async function setupProjectGit(gitPlan) {
  if (gitPlan.mode === "preserve-repository") {
    // Record a completed first run only for an independent, regular .git
    // directory. Future reruns can then honor intentional domain removals.
    if (gitPlan.markInitialized) {
      git(["config", "--local", "proti.initialized", "true"]);
    }
    console.log("✓ Existing Git repository and history preserved");
    return false;
  }

  if (gitPlan.mode === "new-repository") {
    git(["init", "-b", "main"]);
    git(["config", "--local", "proti.initialized", "true"]);
    console.log("✓ Initialized a fresh Git repository (no remotes)");
    return true;
  }

  // Explicitly authorized first-time clone only. Save the original Git
  // directory outside this project so the old history stays recoverable.
  const backup = path.join(
    path.dirname(ROOT),
    `${path.basename(ROOT)}-git-backup-${Date.now()}-${process.pid}`,
  );
  await fs.rename(gitPlan.gitPath, backup);
  try {
    git(["init", "-b", "main"]);
    git(["config", "--local", "proti.initialized", "true"]);
    console.log(
      "✓ Initialized independent Git repository (no inherited history or remotes)",
    );
    console.log(`  Previous Git metadata backed up at: ${backup}`);
    return true;
  } catch (error) {
    await fs.rm(gitPlan.gitPath, { recursive: true, force: true });
    await fs.rename(backup, gitPlan.gitPath);
    throw new Error(
      `Git initialization failed; original Git metadata restored. ${error.message}`,
    );
  }
}

// Visual snapshots belong to the site that created them. Never carry the
// proti-demo screenshots into a brand-new generated project's CI baseline.
// This runs only when Git was freshly initialized/reset, not on repeat init.
// Remove PNG baselines without deleting directory structure or unrelated files.
async function clearInheritedVisualBaselines() {
  const snapshots = path.join(ROOT, "web", "e2e", "__screenshots__");
  if (!(await fileExists(snapshots))) return;

  async function clearPngs(directory) {
    let removed = 0;
    for (const entry of await fs.readdir(directory, { withFileTypes: true })) {
      const entryPath = path.join(directory, entry.name);
      if (entry.isDirectory()) {
        removed += await clearPngs(entryPath);
      } else if (entry.isFile() && entry.name.toLowerCase().endsWith(".png")) {
        await fs.rm(entryPath);
        removed++;
      }
    }
    return removed;
  }

  const removed = await clearPngs(snapshots);
  if (removed > 0) {
    console.log(
      `✓ Removed inherited demo visual baselines (${removed} PNG file${removed === 1 ? "" : "s"})`,
    );
  } else {
    console.log("✓ No inherited demo visual baselines to remove");
  }
  console.log(
    "  Generate your site's baselines after seeding: pnpm proti:visual:init",
  );
}

const existingConfig = (await readJson(CONFIG_PATH, {})) ?? {};
const existingWebEnv = await readEnv(WEB_ENV_PATH);
const existingStudioEnv = await readEnv(STUDIO_ENV_PATH);
const existingDevEnv = await readEnv(STUDIO_DEV_ENV_PATH);
const existingProdEnv = await readEnv(STUDIO_PROD_ENV_PATH);
const scriptedAnswers = await readScriptedAnswers();
const scriptedState = { index: 0 };
const rl = scriptedAnswers
  ? null
  : createInterface({ input: process.stdin, output: process.stdout });

try {
  console.log("\nProti project initialization\n");

  // Preflight MUST run before editing files, so an accidental init in the
  // source repository leaves both the working tree and Git history untouched.
  const gitPlan = await inspectProjectGit();
  if (gitPlan.mode === "detach-starter") {
    await confirmHistoryReset(rl, scriptedAnswers, scriptedState);
  }

  const projectName = await prompt(
    rl,
    scriptedAnswers,
    scriptedState,
    "Project name",
    existingConfig.projectName || "Proti Site",
  );
  const packageName = slugify(
    await prompt(
      rl,
      scriptedAnswers,
      scriptedState,
      "Package/project slug",
      existingConfig.packageName || slugify(projectName) || "proti-site",
    ),
  );
  const projectId = await prompt(
    rl,
    scriptedAnswers,
    scriptedState,
    "Sanity project ID",
    existingConfig.sanity?.projectId ||
      existingWebEnv.NEXT_SANITY_PROJECT_ID ||
      existingStudioEnv.SANITY_STUDIO_PROJECT_ID ||
      "",
  );

  if (!/^[a-z0-9-]+$/i.test(projectId)) {
    throw new Error("A valid Sanity project ID is required.");
  }

  const dataset = await prompt(
    rl,
    scriptedAnswers,
    scriptedState,
    "Sanity dataset",
    existingConfig.sanity?.dataset ||
      existingWebEnv.NEXT_SANITY_DATASET ||
      existingStudioEnv.SANITY_STUDIO_DATASET ||
      "production",
  );
  const studioUrl = await prompt(
    rl,
    scriptedAnswers,
    scriptedState,
    "Studio URL used by the Web app",
    existingConfig.sanity?.studioUrl ||
      existingWebEnv.NEXT_SANITY_STUDIO_URL ||
      "http://localhost:3333",
  );
  const previewUrl = normalizeWebUrl(
    await prompt(
      rl,
      scriptedAnswers,
      scriptedState,
      "Development Web URL for Sanity Presentation",
      existingConfig.sanity?.previewUrl ||
        existingDevEnv.SANITY_STUDIO_PREVIEW_URL ||
        existingStudioEnv.SANITY_STUDIO_PREVIEW_URL ||
        "http://localhost:3000",
    ),
  );
  const siteName = await prompt(
    rl,
    scriptedAnswers,
    scriptedState,
    "Initial Site name",
    existingConfig.site?.name || projectName,
  );
  const siteKey = slugify(
    await prompt(
      rl,
      scriptedAnswers,
      scriptedState,
      "Initial Site key",
      existingConfig.site?.key || packageName,
    ),
  );
  const domains = Array.from(
    new Set(
      splitCsv(
        await prompt(
          rl,
          scriptedAnswers,
          scriptedState,
          "Site domains (comma separated)",
          existingConfig.site?.domains?.join(", ") || "localhost",
        ),
      )
        .map(normalizeDomain)
        .filter(Boolean),
    ),
  );

  if (domains.length === 0)
    throw new Error("At least one Site domain is required.");

  // The project's local Git marker distinguishes first-time initialization
  // from a rerun (even when the starter already carries a config file).
  // New Sites always need localhost for dev and CI; established Sites may
  // intentionally remove it without a future init silently restoring it.
  const firstInitialization = gitPlan.firstInitialization ?? true;
  if (firstInitialization && !domains.includes("localhost")) {
    domains.push("localhost");
    console.log("✓ Included localhost for local development and CI");
  }

  domains.forEach(validateDomain);

  const canonicalDomain = normalizeDomain(
    await prompt(
      rl,
      scriptedAnswers,
      scriptedState,
      "Canonical domain",
      existingConfig.site?.canonicalDomain || domains[0] || "",
    ),
  );

  validateDomain(canonicalDomain);

  if (!domains.includes(canonicalDomain)) {
    throw new Error(
      `Canonical domain "${canonicalDomain}" must be included in Site domains.`,
    );
  }

  const productionPreviewUrl = normalizeWebUrl(
    await prompt(
      rl,
      scriptedAnswers,
      scriptedState,
      "Production Web URL for Sanity Presentation (optional)",
      existingConfig.sanity?.productionPreviewUrl ||
        existingProdEnv.SANITY_STUDIO_PREVIEW_URL ||
        suggestedProductionUrl(canonicalDomain),
    ),
    { production: true },
  );

  const defaultLocale = normalizeLocale(
    await prompt(
      rl,
      scriptedAnswers,
      scriptedState,
      "Default locale",
      existingConfig.site?.defaultLocale || "en-us",
    ),
  );

  if (!/^[a-z]{2,3}-[a-z]{2}$/.test(defaultLocale)) {
    throw new Error(
      `Invalid default locale "${defaultLocale}". Use language-region format, e.g. en-us.`,
    );
  }

  const existingLocales =
    existingConfig.site?.locales
      ?.map(({ code, label }) => `${code}:${label}`)
      .join(", ") || "en-us:English (US), es-us:Spanish (US)";
  const locales = parseLocales(
    await prompt(
      rl,
      scriptedAnswers,
      scriptedState,
      "Supported locales as code:label (comma separated)",
      existingLocales,
    ),
  );

  if (!locales.some(({ code }) => code === defaultLocale)) {
    throw new Error(
      `Default locale "${defaultLocale}" must be included in Supported locales.`,
    );
  }

  const config = {
    version: 1,
    projectName,
    packageName,
    sanity: { projectId, dataset, studioUrl, previewUrl, productionPreviewUrl },
    site: {
      name: siteName,
      key: siteKey,
      domains,
      canonicalDomain,
      defaultLocale,
      locales,
    },
  };

  await fs.writeFile(CONFIG_PATH, `${JSON.stringify(config, null, 2)}\n`);
  await writeEnv(
    WEB_ENV_PATH,
    {
      NEXT_SANITY_PROJECT_ID: projectId,
      NEXT_SANITY_DATASET: dataset,
      NEXT_SANITY_STUDIO_URL: studioUrl,
      SANITY_API_READ_TOKEN: existingWebEnv.SANITY_API_READ_TOKEN || "",
      SANITY_API_WRITE_TOKEN: existingWebEnv.SANITY_API_WRITE_TOKEN || "",
      SANITY_REVALIDATE_SECRET: existingWebEnv.SANITY_REVALIDATE_SECRET || "",
    },
    "Proti Web local environment",
  );
  await writeEnv(
    STUDIO_ENV_PATH,
    {
      SANITY_STUDIO_PROJECT_ID: projectId,
      SANITY_STUDIO_DATASET: dataset,
      SANITY_STUDIO_TITLE: projectName,
      SANITY_STUDIO_APP_ID: existingStudioEnv.SANITY_STUDIO_APP_ID || "",
    },
    "Proti Studio local environment",
  );

  await updateModePreviewUrl(
    STUDIO_DEV_ENV_PATH,
    previewUrl,
    "Development Sanity Presentation URL",
  );
  await updateModePreviewUrl(
    STUDIO_PROD_ENV_PATH,
    productionPreviewUrl,
    "Production Sanity Presentation URL (configure after deployment if blank)",
  );

  await updatePackageName(path.join(ROOT, "package.json"), packageName);
  await updatePackageName(
    path.join(ROOT, "web", "package.json"),
    `${packageName}-web`,
  );
  await updatePackageName(
    path.join(ROOT, "studio", "package.json"),
    `${packageName}-studio`,
  );

  const freshRepository = await setupProjectGit(gitPlan);
  if (freshRepository) await clearInheritedVisualBaselines();

  console.log("\n✓ Wrote proti.config.json");
  console.log("✓ Wrote web/.env.local");
  console.log("✓ Wrote studio/.env.local");
  console.log("✓ Wrote studio/.env.development and studio/.env.production");
  if (!productionPreviewUrl) {
    console.log(
      "! Production Presentation URL not set. After Web deployment, run: pnpm proti:configure:production",
    );
  }
  console.log("✓ Updated package names where package.json files exist");
  console.log("\nNext:");
  console.log("  1. Add any required Sanity tokens to web/.env.local.");
  console.log("  2. Run: pnpm proti:seed");
  console.log(
    "     Optional starter content: pnpm proti:seed --starter-content",
  );
  console.log("  3. Run: pnpm proti:check");
  console.log(
    "  4. Run: pnpm proti:visual:init (after seeding; requires Playwright Chromium)",
  );
  console.log("  5. Review and commit the new visual screenshots before CI");
  console.log("  6. Run: pnpm dev:studio");
  console.log("  7. Run: pnpm dev:web");
  console.log(
    "  8. After deploying Web: pnpm proti:configure:production, then redeploy Studio\n",
  );
} finally {
  rl?.close();
}
