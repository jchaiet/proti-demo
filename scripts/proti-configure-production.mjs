import fs from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { createInterface } from "node:readline/promises";

const ROOT = process.cwd();
const CONFIG_PATH = path.join(ROOT, "proti.config.json");
const PRODUCTION_ENV_PATH = path.join(ROOT, "studio", ".env.production");

function normalizeProductionUrl(input) {
  const value = String(input ?? "").trim();
  let url;
  try {
    url = new URL(value);
  } catch {
    throw new Error(
      "Provide a valid production Web URL, e.g. https://site.vercel.app.",
    );
  }
  if (
    url.protocol !== "https:" ||
    !url.hostname ||
    url.username ||
    url.password ||
    url.search ||
    url.hash ||
    url.pathname !== "/" ||
    ["localhost", "127.0.0.1", "::1", "[::1]"].includes(
      url.hostname.toLowerCase(),
    )
  ) {
    throw new Error(
      "Production Web URL must be a public HTTPS origin without a path, query, or credentials.",
    );
  }
  return url.origin;
}

function normalizeDomain(value) {
  return String(value ?? "")
    .trim()
    .toLowerCase()
    .replace(/^https?:\/\//, "")
    .replace(/\/.*$/, "")
    .replace(/\.$/, "");
}

async function readScriptedUrl() {
  if (process.stdin.isTTY) {
    const rl = createInterface({
      input: process.stdin,
      output: process.stdout,
    });
    try {
      return (
        await rl.question("Production Web URL for Sanity Presentation: ")
      ).trim();
    } finally {
      rl.close();
    }
  }
  let input = "";
  for await (const chunk of process.stdin) input += chunk;
  return input.trim().split(/\r?\n/)[0] || "";
}

function parseArgs(argv) {
  let input = "";
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === "--url") {
      input = argv[++i] || "";
    } else if (argv[i].startsWith("--url=")) {
      input = argv[i].slice("--url=".length);
    } else {
      throw new Error(
        `Unknown argument "${argv[i]}". Use --url=https://site.vercel.app`,
      );
    }
  }
  return input;
}

let config;
try {
  config = JSON.parse(await fs.readFile(CONFIG_PATH, "utf8"));
} catch {
  throw new Error(
    'Missing or invalid proti.config.json. Run "pnpm proti:init" first.',
  );
}
if (!config.sanity || !config.site) {
  throw new Error('Invalid proti.config.json. Run "pnpm proti:init" first.');
}

const raw = parseArgs(process.argv.slice(2)) || (await readScriptedUrl());
const productionPreviewUrl = normalizeProductionUrl(
  raw || config.sanity.productionPreviewUrl,
);

const original = await fs.readFile(PRODUCTION_ENV_PATH, "utf8").catch((e) => {
  if (e.code === "ENOENT") return "";
  throw e;
});
const lines = original
  ? original
      .split(/\r?\n/)
      .filter((line) => !/^\s*SANITY_STUDIO_PREVIEW_URL\s*=/.test(line))
  : [
      "# Production Sanity Presentation URL",
      "# Generated by Proti; non-secret public configuration",
      "",
    ];
while (lines.length && lines.at(-1) === "") lines.pop();
lines.push(`SANITY_STUDIO_PREVIEW_URL=${productionPreviewUrl}`, "");

config.sanity.productionPreviewUrl = productionPreviewUrl;
await fs.mkdir(path.dirname(PRODUCTION_ENV_PATH), { recursive: true });
await fs.writeFile(PRODUCTION_ENV_PATH, lines.join("\n"));
await fs.writeFile(CONFIG_PATH, JSON.stringify(config, null, 2) + "\n");

console.log(`✓ Production Presentation URL: ${productionPreviewUrl}`);
console.log("✓ Updated studio/.env.production and proti.config.json");
const domain = new URL(productionPreviewUrl).hostname.toLowerCase();
if (
  !(config.site.domains || []).some((item) => normalizeDomain(item) === domain)
) {
  console.warn(
    `! The domain ${domain} is not in proti.config.json site.domains.`,
  );
  console.warn(
    "  Update your site's domains and the published Sanity Site document before deploying Web.",
  );
}
console.log(
  "Next: redeploy Studio with pnpm --filter ./studio exec sanity deploy",
);
console.log(
  "No Vercel redeployment is required for a Studio Presentation URL change.",
);
